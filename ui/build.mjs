import { build } from "esbuild";
import { readFileSync, readdirSync } from "node:fs";
import { fileURLToPath } from "node:url";

const glassLicense = readFileSync(new URL("./shared/assets/licenses/liquid-glass.txt", import.meta.url), "utf8");
const views = readdirSync(new URL("./views/", import.meta.url), { withFileTypes: true })
  .filter((entry) => entry.isDirectory()).map((entry) => entry.name).sort();

await build({
  absWorkingDir: fileURLToPath(new URL("./", import.meta.url)),
  entryPoints: Object.fromEntries(views.map((name) => [`${name}/bundle`, `views/${name}/main.jsx`])),
  outdir: "dist",
  bundle: true,
  platform: "browser",
  format: "iife",
  target: "es2020",
  jsx: "automatic",
  minify: true,
  legalComments: "inline",
  define: { "process.env.NODE_ENV": '"production"' },
  loader: { ".svg": "dataurl", ".png": "dataurl" },
  banner: { js: `/* Generated by npm --prefix ui run build:ui. Edit ui/views/ or ui/shared/ instead. */\n/*! @samasante/liquid-glass\n${glassLicense} */` },
  logLevel: "info",
});
